<?php

namespace Tests\Integration;

use Classes\Upgrades\Routines\Upgrade_v1_18_2_to_v1_18_3;
use Doctrine\DBAL\Connection;
use Doctrine\DBAL\DriverManager;
use Doctrine\DBAL\Tools\DsnParser;
use Symfony\Component\Console\Output\BufferedOutput;

require_once __DIR__.'/GscSearchTypeUpgradeTest.php';

/** Explicit opt-in database; every test owns and removes a random schema. */
class GscSearchTypeUpgradePostgresTest extends GscSearchTypeUpgradeTest
{
    private ?string $schema = null;

    protected function connectFixture(): Connection
    {
        $dsn = getenv('GSC_UPGRADE_TEST_DSN');
        if (!$dsn) $this->markTestSkipped('Set GSC_UPGRADE_TEST_DSN to an isolated PostgreSQL test database.');
        $params = (new DsnParser(['postgres' => 'pdo_pgsql', 'postgresql' => 'pdo_pgsql']))->parse($dsn);
        $params['wrapperClass'] = GscUpgradeSqliteConnection::class;
        $conn = DriverManager::getConnection($params);
        $this->schema = 'gsc_upgrade_test_'.bin2hex(random_bytes(8));
        $conn->executeStatement('CREATE SCHEMA '.$this->schema);
        $conn->executeStatement('SET search_path TO '.$this->schema);
        return $conn;
    }

    protected function fixtureSql(string $sql): string
    {
        return str_replace('id INTEGER PRIMARY KEY', 'id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', $sql);
    }

    protected function tearDown(): void
    {
        if ($this->schema && isset($this->conn)) {
            if ($this->conn->isTransactionActive()) $this->conn->rollBack();
            $this->conn->executeStatement('DROP SCHEMA '.$this->schema.' CASCADE');
            $this->conn->close();
        }
        parent::tearDown();
    }

    public function testRepresentativeVolumePreservesObservationsAndReferences(): void
    {
        // 612702 reproduces the observed configuration count. Explicitly opt in:
        // the duplicate loop can legitimately take over an hour at that volume.
        $count = max(2001, min(1000000, (int)(getenv('GSC_UPGRADE_TEST_CONFIGS') ?: 2001)));
        $duplicates = (int) floor($count * 273566 / 612702);
        $survivors = $count - $duplicates;
        $this->seed(1, 1);
        $this->conn->executeStatement('UPDATE metric_configs SET name = ? WHERE id = 1', ['metric_1']);
        $this->conn->executeStatement("INSERT INTO metric_configs (id, channel, name, period, dimension_set_id, config_signature)
            SELECT i, 1, 'metric_' || CASE WHEN i > :survivors THEN i - :survivors ELSE i END, 'daily', dimension_set_id, 'old_' || i
            FROM generate_series(2, :count) i CROSS JOIN metric_configs WHERE id = 1", ['survivors' => $survivors, 'count' => $count]);
        $this->conn->executeStatement("INSERT INTO metrics (id, metric_config_id, dimensions_hash, metric_date, value)
            SELECT i, i, dimensions_hash, metric_date, CASE WHEN i > :survivors THEN 9 ELSE 7 END
            FROM generate_series(2, :count) i CROSS JOIN metrics WHERE id = 1", ['survivors' => $survivors, 'count' => $count]);
        $this->conn->executeStatement('INSERT INTO channeled_metrics (id, metric_id, dimension_set_id)
            SELECT i, i, dimension_set_id FROM generate_series(2, ?) i CROSS JOIN channeled_metrics WHERE id = 1', [$count]);
        $this->conn->executeStatement('ALTER TABLE metrics ADD FOREIGN KEY (metric_config_id) REFERENCES metric_configs(id)');
        $this->conn->executeStatement('ALTER TABLE channeled_metrics ADD FOREIGN KEY (metric_id) REFERENCES metrics(id)');
        $output = new BufferedOutput();
        (new Upgrade_v1_18_2_to_v1_18_3())->up($this->em, $output);
        $this->assertSame($survivors, (int)$this->conn->fetchOne('SELECT COUNT(*) FROM metric_configs'));
        $this->assertSame($survivors, (int)$this->conn->fetchOne('SELECT COUNT(*) FROM metrics'));
        $this->assertSame($survivors, (int)$this->conn->fetchOne('SELECT COUNT(*) FROM channeled_metrics'));
        $this->assertSame((float)(7 * $survivors + 2 * $duplicates), (float)$this->conn->fetchOne('SELECT SUM(value) FROM metrics'));
        $this->assertSame(0, (int)$this->conn->fetchOne('SELECT COUNT(*) FROM metrics m JOIN metric_configs mc ON mc.id = m.metric_config_id JOIN dimension_sets ds ON ds.id = mc.dimension_set_id WHERE m.dimensions_hash <> ds.hash'));
        $this->assertStringContainsString('merged '.$duplicates.' duplicates without summing', $output->fetch());
    }
}
